const formatToLocalTime = (dateInput: string | number[] | number | null | undefined): string => {
    if (dateInput == null || dateInput === '') return ''

    try {
        if (Array.isArray(dateInput)) {
            const hours = String(dateInput[3] ?? 0).padStart(2, '0')
            const minutes = String(dateInput[4] ?? 0).padStart(2, '0')
            return `${hours}:${minutes}`
        }

        const dateStr = String(dateInput).trim()

        if (/^\d{1,2}:\d{2}(:\d{2})?$/.test(dateStr)) {
            const [hours, minutes] = dateStr.split(':')
            return `${hours.padStart(2, '0')}:${minutes}`
        }

        if (dateStr.includes(',')) {
            const parts = dateStr.split(',').map(Number)
            const hours = String(parts[3] ?? 0).padStart(2, '0')
            const minutes = String(parts[4] ?? 0).padStart(2, '0')
            return `${hours}:${minutes}`
        }

        if (/[zZ]|[+-]\d{2}:\d{2}$/.test(dateStr)) {
            const parsedDate = new Date(dateStr)
            if (!Number.isNaN(parsedDate.getTime())) {
                return parsedDate.toLocaleTimeString('ko-KR', {
                    hour: '2-digit',
                    minute: '2-digit',
                    hour12: false,
                    timeZone: 'Asia/Seoul',
                })
            }
        }

        const normalizedMatches = dateStr.match(/\d+/g)
        if (normalizedMatches && normalizedMatches.length >= 5) {
            const hours = String(parseInt(normalizedMatches[3], 10)).padStart(2, '0')
            const minutes = String(parseInt(normalizedMatches[4], 10)).padStart(2, '0')
            return `${hours}:${minutes}`
        }

        // ?? 耳?댁뒪 1: ?대? "HH:mm" ?뺥깭 ??????????????????????????????
        if (/^\d{2}:\d{2}$/.test(dateStr)) {
            debugLog('formatToLocalTime', '?대? ?뺤젣??HH:mm ?뺤떇 ??洹몃?濡?諛섑솚', dateStr)
            return dateStr
        }

        let year = 2026, month = 5, day = 26, hours = 0, minutes = 0

        // ?? 耳?댁뒪 2: 諛곗뿴 ?뺥깭 [year, month, day, hour, minute] ??????
        if (Array.isArray(dateInput)) {
            const parts = dateInput as number[]
            year    = parts[0] ?? 2026
            month   = parts[1] ?? 5
            day     = parts[2] ?? 26
            hours   = parts[3] ?? 0
            minutes = parts[4] ?? 0
            debugLog('formatToLocalTime', '諛곗뿴 ?뺥깭 ?뚯떛', { year, month, day, hours, minutes })

        } else if (typeof dateStr === 'string' && dateStr.includes(',')) {
            // ?? 耳?댁뒪 2-b: ?쇳몴濡??댁뼱吏?臾몄옄??"2026,5,26,1,14" ??????
            const parts = dateStr.split(',').map(Number)
            year    = parts[0] ?? 2026
            month   = parts[1] ?? 5
            day     = parts[2] ?? 26
            hours   = parts[3] ?? 0
            minutes = parts[4] ?? 0
            debugLog('formatToLocalTime', '?쇳몴 臾몄옄???뚯떛', { year, month, day, hours, minutes })

        } else {
            // ?? 耳?댁뒪 3/4: ISO 臾몄옄???먮뒗 ?쒓컙 臾몄옄????????????????????
            // 釉뚮씪?곗????먮룞 UTC ?댁꽍??留됯린 ?꾪빐 ?뺢퇋?앹쑝濡??レ옄留?異붿텧?⑸땲??
            const matches = dateStr.match(/\d+/g)

            if (!matches) {
                debugLog('formatToLocalTime', '?レ옄 異붿텧 ?ㅽ뙣 ???먮Ц 諛섑솚', dateStr)
                return dateStr
            }

            if (matches.length >= 5) {
                // "2026-05-26T01:14:00" ?뺥깭
                year    = parseInt(matches[0], 10)
                month   = parseInt(matches[1], 10)
                day     = parseInt(matches[2], 10)
                hours   = parseInt(matches[3], 10)
                minutes = parseInt(matches[4], 10)
                debugLog('formatToLocalTime', 'ISO 臾몄옄???뚯떛', { year, month, day, hours, minutes })

            } else if (matches.length >= 2) {
                // "01:14:00" 泥섎읆 ?쒓컙 ?곗씠?곕쭔 ?섏뼱??寃쎌슦
                hours   = parseInt(matches[0], 10)
                minutes = parseInt(matches[1], 10)
                debugLog('formatToLocalTime', '?쒓컙 ?꾩슜 ?뚯떛', { hours, minutes })

            } else {
                debugLog('formatToLocalTime', '?뚯떛 遺덇? ???먮Ц 諛섑솚', dateStr)
                return dateStr
            }
        }

        // ?? ?듭떖 蹂댁젙: 誘멸뎅 ???쒓뎅 ?쒖감 +KST_OFFSET_HOURS ?곸슜 ????????
        // Date ?앹꽦?먯뿉 '濡쒖뺄 ?쒓컙' ?レ옄瑜?吏곸젒 ?섍꺼??釉뚮씪?곗? UTC 蹂?섏쓣 ?고쉶?⑸땲??
        const localDate = new Date(year, month - 1, day, hours + KST_OFFSET_HOURS, minutes)

        const finalHours   = String(localDate.getHours()).padStart(2, '0')
        const finalMinutes = String(localDate.getMinutes()).padStart(2, '0')
        const result       = `${finalHours}:${finalMinutes}`

        debugLog('formatToLocalTime', `?먮낯 ${hours}:${String(minutes).padStart(2,'0')} ??蹂댁젙 ??KST ${result}`)

        return result

    } catch (e) {
        debugLog('formatToLocalTime', '蹂??以??덉쇅 諛쒖깮', e)
        return String(dateInput)
    }
}

